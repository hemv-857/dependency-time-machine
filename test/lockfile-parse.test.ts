import { describe, expect, it } from 'vitest';
import {
  parsePackageLock,
  parseRequirementsTxt,
  parseYarnLock,
  parsePnpmLock,
  parsePackageJson,
} from '@/core/lockfile/parse';

describe('package-lock.json', () => {
  it('parses v3 packages map, preferring shallowest', () => {
    const lock = parsePackageLock(
      JSON.stringify({
        name: 'app',
        lockfileVersion: 3,
        packages: {
          '': { name: 'app', version: '1.0.0' },
          'node_modules/lodash': { version: '4.17.21' },
          'node_modules/foo/node_modules/lodash': { version: '3.0.0' },
          'node_modules/@babel/core': { version: '7.24.0' },
        },
      })
    );
    expect(lock.packages).toEqual({ lodash: '4.17.21', '@babel/core': '7.24.0' });
  });

  it('parses v1 recursive dependencies tree', () => {
    const lock = parsePackageLock(
      JSON.stringify({
        lockfileVersion: 1,
        dependencies: {
          lodash: { version: '4.17.15' },
          bundled: {
            version: '1.0.0',
            dependencies: { tiny: { version: '2.0.0' } },
          },
        },
      })
    );
    expect(lock.packages).toEqual({ lodash: '4.17.15', bundled: '1.0.0', tiny: '2.0.0' });
  });
});

describe('yarn.lock', () => {
  it('parses classic v1 blocks with multiple specs', () => {
    const lock = parseYarnLock(`
# THIS IS AN AUTOGENERATED FILE
lodash@^4.17.15, lodash@^4.0.0:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#abc"

"@babel/core@^7.0.0":
  version "7.12.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.12.0.tgz#def"
`);
    expect(lock.packages).toEqual({ lodash: '4.17.21', '@babel/core': '7.12.0' });
  });

  it('parses berry entries with npm: protocol', () => {
    const lock = parseYarnLock(`
__metadata:
  version: 8

"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"

"@scope/pkg@npm:^1.2.0":
  version: 1.2.3
  resolution: "@scope/pkg@npm:1.2.3"
`);
    expect(lock.packages).toEqual({ lodash: '4.17.21', '@scope/pkg': '1.2.3' });
  });
});

describe('pnpm-lock.yaml', () => {
  it('parses packages section with registry prefix and peer suffixes', () => {
    const lock = parsePnpmLock(`
lockfileVersion: '6.0'

dependencies:
  lodash: 4.17.21

packages:

  /lodash@4.17.21:
    resolution: {integrity: sha512-v2k}

  /foo@1.0.0(bar@2.0.0):
    resolution: {integrity: sha512-xyz}

  '@scope/things@3.2.1':
    resolution: {integrity: sha512-qrs}
`);
    expect(lock.packages).toEqual({ lodash: '4.17.21', foo: '1.0.0', '@scope/things': '3.2.1' });
  });
});

describe('requirements.txt', () => {
  it('parses pinned versions, normalizing names', () => {
    const lock = parseRequirementsTxt(`
# comment
requests==2.31.0 --hash=sha256:abc
Django==4.2
flask[async]==3.0.0
numpy>=1.0
`);
    expect(lock.packages).toEqual({ requests: '2.31.0', django: '4.2', flask: '3.0.0' });
  });
});

describe('package.json manifest', () => {
  it('extracts deps, scripts and own identity', () => {
    const m = parsePackageJson(
      JSON.stringify({
        name: 'left-pad',
        version: '1.3.0',
        scripts: { test: 'mocha' },
        dependencies: { a: '^1.0.0' },
        devDependencies: { mocha: '^10' },
      })
    );
    expect(m.ownName).toBe('left-pad');
    expect(m.dependencies.a).toBe('^1.0.0');
    expect(m.dependencies.mocha).toBe('^10');
    expect(m.scripts?.test).toBe('mocha');
  });
});

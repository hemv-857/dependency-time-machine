import { describe, expect, it } from 'vitest';
import { parseCargoLock, parseCargoToml, parseGoMod, parseGoSum, parseLockfileFrom, parseManifestFrom } from '@/core/lockfile/parse';
import { buildSecurityLens } from '@/core/security/osv';

/** Go and Rust pins. Both formats are whitespace/TOML rather than JSON. */
const GO_SUM = `github.com/davecgh/go-spew v1.1.1 h1:J7Y8YcW2NihsgmVo/mv3lAwl/skON4iLHjSsI+c5H38=
github.com/davecgh/go-spew v1.1.1/go.mod h1:J7Y8YcW2NihsgmVo/mv3lAwl/skON4iLHjSsI+c5H38=
github.com/gin-gonic/gin v1.9.1 h1:4idEAncQnU5cB7BeOkPtxqCS6t8LozoNvr8H1On+3cg=
golang.org/x/net v0.17.0 h1:pVaXccu2ozPjCXewfr1S7xza/zcXTity9cCdXQYSjIM=
golang.org/x/net v0.17.0/go.mod h1:NxSsAGuq816PNPmqtQdLE42eU2Fs7NoRIZrHJAlaCOE=
// a comment line
golang.org/x/text v0.13.0/go.mod h1:ablQoSUd0tRdKxZewP80B+Bsx59MF+J4t6p/uy4wA=
`;

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "smallvec"
version = "1.6.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "serde"
version = "1.0.130"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "my-app"
version = "0.1.0"

[[patch.unused]]
name = "ignored"
version = "9.9.9"
`;

describe('parseGoSum', () => {
  it('extracts module pins and strips the v prefix', () => {
    const lf = parseGoSum(GO_SUM);
    expect(lf.ecosystem).toBe('go');
    expect(lf.path).toBe('go.sum');
    expect(lf.packages['golang.org/x/net']).toBe('0.17.0');
    expect(lf.packages['github.com/gin-gonic/gin']).toBe('1.9.1');
  });

  it('ignores /go.mod duplicate lines and comments', () => {
    const lf = parseGoSum(GO_SUM);
    // x/text only has a /go.mod line, so it must not be treated as a dependency
    expect(lf.packages['golang.org/x/text']).toBeUndefined();
    expect(Object.values(lf.packages).every((v) => !v.includes('/go.mod'))).toBe(true);
  });

  it('is not confused by the module path containing slashes or dots', () => {
    const lf = parseGoSum('gopkg.in/yaml.v3 v3.0.1 h1:fxVm/GzAzEWqLHuvctI91KS9hhNmmWOoWu0XTYJS7CA=\n');
    expect(lf.packages['gopkg.in/yaml.v3']).toBe('3.0.1');
  });

  it('handles an empty or junk file without throwing', () => {
    expect(parseGoSum('').packages).toEqual({});
    expect(parseGoSum('not a lockfile\n\n').packages).toEqual({});
  });
});

describe('parseCargoLock', () => {
  it('reads every [[package]] block', () => {
    const lf = parseCargoLock(CARGO_LOCK);
    expect(lf.ecosystem).toBe('cargo');
    expect(lf.path).toBe('Cargo.lock');
    expect(lf.packages).toEqual({ smallvec: '1.6.0', serde: '1.0.130', 'my-app': '0.1.0' });
  });

  it('does not leak packages from non-package tables', () => {
    expect(parseCargoLock(CARGO_LOCK).packages['ignored']).toBeUndefined();
  });

  it('keeps prerelease versions intact', () => {
    const lf = parseCargoLock('[[package]]\nname = "tokio"\nversion = "1.0.0-beta.1"\n');
    expect(lf.packages['tokio']).toBe('1.0.0-beta.1');
  });

  it('handles an empty lockfile', () => {
    expect(parseCargoLock('').packages).toEqual({});
    expect(parseCargoLock('# only a comment\n').packages).toEqual({});
  });
});

describe('parseLockfileFrom picks the new formats', () => {
  const read2 = (p: string) =>
    ({ 'go.sum': GO_SUM, 'Cargo.lock': CARGO_LOCK } as Record<string, string>)[p] ?? null;

  it('selects go.sum', () => {
    expect(parseLockfileFrom(['go.mod', 'go.sum'], read2)?.ecosystem).toBe('go');
  });
  it('selects Cargo.lock', () => {
    expect(parseLockfileFrom(['Cargo.toml', 'Cargo.lock'], read2)?.ecosystem).toBe('cargo');
  });
  it('prefers package-lock.json over everything else', () => {
    const files = ['package-lock.json', 'go.sum', 'Cargo.lock', 'yarn.lock'];
    const read = (p: string) => (p === 'package-lock.json' ? '{"packages":{"":{"name":"x"},"node_modules/a":{"version":"1.0.0"}}}' : read2(p));
    expect(parseLockfileFrom(files, read)?.ecosystem).toBe('npm');
  });
});

describe('manifests for go and rust', () => {
  it('reads the module path from go.mod', () => {
    const m = parseGoMod('module github.com/acme/widget\n\ngo 1.21\n\nrequire (\n\tgolang.org/x/net v0.17.0\n)\n');
    expect(m.ownName).toBe('github.com/acme/widget');
    expect(m.ecosystem).toBe('go');
  });

  it('reads name+version from the [package] table of Cargo.toml', () => {
    const m = parseCargoToml('[package]\nname = "widget"\nversion = "0.3.1"\nedition = "2021"\n\n[dependencies]\nsmallvec = "1.6"\n');
    expect(m.ownName).toBe('widget');
    expect(m.ownVersion).toBe('0.3.1');
    // a `name` under [dependencies] must not win over [package]
    expect(m.ownName).not.toBe('smallvec');
  });

  it('is reachable through parseManifestFrom', () => {
    const read = (p: string) => (p === 'go.mod' ? 'module github.com/acme/widget\n' : null);
    expect(parseManifestFrom(['go.mod'], read)?.ownName).toBe('github.com/acme/widget');
  });
});

describe('OSV coverage for the new ecosystems', () => {
  it('sends the right OSV ecosystem name for go and cargo', async () => {
    const bodies: string[] = [];
    const capture = (async (_url: string, init?: RequestInit) => {
      bodies.push(String(init?.body ?? ''));
      return Response.json({ results: [] });
    }) as unknown as typeof fetch;

    const go = parseGoSum(GO_SUM);
    await buildSecurityLens(go, go, capture);
    expect(bodies.join(' ')).toContain('"ecosystem":"Go"');

    const rs = parseCargoLock(CARGO_LOCK);
    await buildSecurityLens(rs, rs, capture);
    expect(bodies.join(' ')).toContain('"ecosystem":"crates.io"');
  });

  it('builds a lens for a go lockfile using a stubbed OSV', async () => {
    // single-module lockfile so the positional OSV mapping is unambiguous
    const before = parseGoSum('golang.org/x/net v0.17.0 h1:aaa=\n');
    const after = parseGoSum('golang.org/x/net v0.23.0 h1:bbb=\n');
    const fetchImpl = (async () =>
      Response.json({
        results: [{ vulns: [{ id: 'GHSA-go-1', severity: 'HIGH', summary: 'net vuln' }] }],
      })) as unknown as typeof fetch;

    const lens = await buildSecurityLens(before, after, fetchImpl);
    expect(lens.available).toBe(true);
    expect(lens.then.map((a) => a.id)).toEqual(['GHSA-go-1']);
    expect(lens.then[0].packages).toEqual(['golang.org/x/net']);
  });

  it('returns an unavailable lens for an ecosystem OSV does not index', async () => {
    const lf = { ecosystem: 'unknown' as const, path: 'x', packages: {} };
    const lens = await buildSecurityLens(lf, lf, (async () => Response.json({})) as unknown as typeof fetch);
    expect(lens.available).toBe(false);
  });
});